// ---------- numbering pass: assign n to every claim, fill NOTES ----------
(function number() {
  let k = 0;
  const reg = (obj) => { k += 1; obj.n = k; NOTES.push({ n: k, label: obj.label, note: obj.note }); };
  for (const b of BLOCKS) {
    if (b[0] === "claim") reg(b[1]);
    else if (b[0] === "mix") for (const it of b[1]) if (isClaim(it)) reg(it);
  }
})();

// ---------- paragraph helpers ----------
function H1(t) { return new Paragraph({ heading: HeadingLevel.HEADING_1, children: [new TextRun(t)] }); }
function H2(t) { return new Paragraph({ heading: HeadingLevel.HEADING_2, children: [new TextRun(t)] }); }
function P(t) { return new Paragraph({ spacing: { after: 140, line: 300 }, alignment: AlignmentType.JUSTIFIED, children: [new TextRun({ text: t })] }); }
function claimInlineRuns(obj) {
  return [
    new TextRun({ text: obj.c, highlight: "yellow", color: "7A0000" }),
    new TextRun({ text: ` [${obj.n}]`, superScript: true, bold: true, color: "B00000" }),
  ];
}
function notePara(obj) {
  return new Paragraph({
    spacing: { after: 150 }, indent: { left: 360 },
    border: { left: { style: BorderStyle.SINGLE, size: 18, color: "B00000", space: 8 } },
    children: [
      new TextRun({ text: `[${obj.n}] `, bold: true, color: "B00000", size: 18 }),
      new TextRun({ text: labelText(obj.label) + " — ", bold: true, color: "B00000", size: 18 }),
      new TextRun({ text: obj.note, italics: true, color: "B00000", size: 18 }),
    ],
  });
}
function figPara(file, w, h) {
  return new Paragraph({ alignment: AlignmentType.CENTER, spacing: { before: 80, after: 40 },
    children: [new ImageRun({ type: "png", data: fs.readFileSync(`${FIG}/${file}`), transformation: { width: w, height: h } })] });
}
function capPara(t) {
  return new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 180 },
    children: [new TextRun({ text: t, italics: true, size: 18, color: "555555" })] });
}
function bannerPara(t) {
  return new Paragraph({ spacing: { before: 80, after: 200 }, shading: { type: "clear", fill: "FFF3CD" },
    border: { top: { style: BorderStyle.SINGLE, size: 12, color: "B00000" }, bottom: { style: BorderStyle.SINGLE, size: 12, color: "B00000" },
      left: { style: BorderStyle.SINGLE, size: 12, color: "B00000" }, right: { style: BorderStyle.SINGLE, size: 12, color: "B00000" } },
    children: [new TextRun({ text: t, bold: true, color: "B00000", size: 20 })] });
}

// ---------- render a manuscript (withNotes = inline notes or not) ----------
function renderManuscript(withNotes) {
  const out = [];
  const banner = withNotes ? BANNER_WITH : BANNER_NO;
  for (const b of BLOCKS) {
    switch (b[0]) {
      case "title":
        out.push(new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 60 },
          children: [new TextRun({ text: TITLE, bold: true, size: 28 })] }));
        break;
      case "authors":
        out.push(new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 60 },
          children: [new TextRun({ text: "[[Author Name(s)]] · [[Affiliation(s)]] · [[Corresponding email]]", italics: true, size: 20, color: "555555" })] }));
        out.push(bannerPara(banner));
        break;
      case "h1": out.push(H1(b[1])); break;
      case "h2": out.push(H2(b[1])); break;
      case "p": out.push(P(b[1])); break;
      case "green":
        out.push(new Paragraph({ spacing: { before: 60, after: 60 }, children: [new TextRun({ text: b[1], bold: true, color: "1B6B2F" })] }));
        break;
      case "keywords":
        out.push(new Paragraph({ spacing: { after: 200 }, children: [
          new TextRun({ text: "Keywords: ", bold: true }),
          new TextRun({ text: "Tele-nursing; Wearable health devices; Chronic disease management; Patient safety monitoring; Remote healthcare analytics" }),
        ] }));
        break;
      case "fig": out.push(figPara(b[1], b[2], b[3])); out.push(capPara(b[4])); break;
      case "refs":
        out.push(H1("References"));
        REFS.forEach((r, i) => out.push(new Paragraph({ spacing: { after: 80 }, children: [new TextRun({ text: `[${i + 1}] ${r}`, size: 20 })] })));
        break;
      case "claim":
        out.push(new Paragraph({ spacing: { after: withNotes ? 30 : 140, line: 300 }, alignment: AlignmentType.JUSTIFIED, children: claimInlineRuns(b[1]) }));
        if (withNotes) out.push(notePara(b[1]));
        break;
      case "mix": {
        const kids = [];
        for (const it of b[1]) kids.push(...(isClaim(it) ? claimInlineRuns(it) : [new TextRun({ text: it.t })]));
        out.push(new Paragraph({ spacing: { after: withNotes ? 30 : 140, line: 300 }, alignment: AlignmentType.JUSTIFIED, children: kids }));
        if (withNotes) for (const it of b[1]) if (isClaim(it)) out.push(notePara(it));
        break;
      }
    }
  }
  return out;
}

